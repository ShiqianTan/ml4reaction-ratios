"""P4d: multi-scale RR -> sequence -> Tg delta-learning.

End-to-end pipeline demonstration using *real* inputs:

  real r1, r2 (RRMaster)  ->  Mayo-Lewis sequence descriptors
  real homopolymer Tg1, Tg2 (PolyInfo, matched by monomer name)
  Fox / Gordon-Taylor composition baseline
  delta-learning model on sequence descriptors to correct the baseline

Because experimental radical-copolymer Tg with known composition is not yet in
the assembled data (PolyInfo `-alt-` entries are dominated by step-growth
polymers), the *target* copolymer Tg is generated by a documented dyad/sequence
model  (Gordon-Taylor + blockiness interaction).  This is a controlled
simulation that validates the methodology; it is flagged as such.

Run: python3 src/p4_delta_learning.py
"""
from __future__ import annotations

import json
import numpy as np
import pandas as pd

from common import STANDARDIZED, PROJECTS
from p4_sequence import mayo_lewis, sequence_descriptors
from p4_tg_data import load_polyinfo, inner_name

P4 = PROJECTS / "P4_sequence_tg"
GAMMA = 0.15      # blockiness interaction strength (simulation)
SIGMA = 3.0       # measurement noise (deg C)


def matched_pairs():
    x = load_polyinfo()
    mono = x[~x.polymer_name.astype(str).str.contains("alt|co")]
    tg = {inner_name(n).lower(): (r.Tg_C, r.smiles)
          for n, r in mono.set_index("polymer_name").iterrows()}
    rr = pd.read_parquet(STANDARDIZED / "rrmaster_v1.parquet")
    rr = rr[rr.ln_r1.notna() & rr.ln_r2.notna()].drop_duplicates(
        "canonical_pair_id")
    rows = []
    for _, r in rr.iterrows():
        k1, k2 = str(r.monomer_1_name).strip().lower(), \
            str(r.monomer_2_name).strip().lower()
        if k1 in tg and k2 in tg:
            rows.append({"pair_id": r.canonical_pair_id,
                         "m1": r.monomer_1_name, "m2": r.monomer_2_name,
                         "r1": r.r1, "r2": r.r2,
                         "Tg1": tg[k1][0], "Tg2": tg[k2][0]})
    return pd.DataFrame(rows)


def build():
    pairs = matched_pairs()
    rng = np.random.default_rng(0)
    rows = []
    for f1 in [0.2, 0.35, 0.5, 0.65, 0.8]:
        s = sequence_descriptors(pairs.r1.values, pairs.r2.values, f1)
        F1 = s["F1"]
        T1 = pairs.Tg1.values + 273.15
        T2 = pairs.Tg2.values + 273.15
        # mole-fraction Fox baseline (Kelvin)
        Tg_fox_K = 1.0 / (F1 / T1 + (1 - F1) / T2)
        dT = np.abs(T1 - T2)
        seq_term = GAMMA * (s["blockiness"] - 1.0) * dT
        noise = rng.normal(0, SIGMA, len(pairs))
        Tg_true = Tg_fox_K + seq_term + noise
        rows.append(pd.DataFrame({
            "pair_id": pairs.pair_id, "f1": f1, "F1": F1,
            "Tg1": T1 - 273.15, "Tg2": T2 - 273.15,
            "Tg_fox": Tg_fox_K - 273.15,
            "residual_true": seq_term + noise,
            "Tg_true": Tg_true - 273.15,
            **{k: s[k] for k in ["P11", "P12", "P21", "P22", "blockiness",
                                 "alternation", "L1", "L2", "seq_entropy",
                                 "dyad_11", "dyad_12", "dyad_21", "dyad_22"]}}))
    return pd.concat(rows, ignore_index=True)


FEATS = ["F1", "Tg1", "Tg2", "blockiness", "alternation", "L1", "L2",
         "seq_entropy", "dyad_11", "dyad_12", "dyad_21", "dyad_22", "P11",
         "P12", "P21", "P22"]


def main():
    from sklearn.linear_model import Ridge
    from sklearn.ensemble import RandomForestRegressor
    from sklearn.metrics import r2_score
    from sklearn.model_selection import LeaveOneGroupOut
    from sklearn.base import clone

    df = build()
    print(f"pairs={df.pair_id.nunique()}  rows={len(df)}")
    base = df.Tg_fox.to_numpy(float)
    y = df.Tg_true.to_numpy(float)
    X = df[FEATS].to_numpy(float)
    groups = df.pair_id.values

    out = {"n_pairs": int(df.pair_id.nunique()), "n_rows": int(len(df)),
           "gamma_sim": GAMMA, "sigma_sim": SIGMA,
           "baseline_Fox_MAE_C": round(float(np.mean(np.abs(y - base))), 3),
           "baseline_Fox_RMSE_C": round(float(np.sqrt(np.mean((y - base) ** 2))), 3)}
    print("Fox baseline MAE:", out["baseline_Fox_MAE_C"])

    # delta-learning: predict residual = Tg_true - Fox  (leave-pair-out)
    for name, model in [("ridge", Ridge(alpha=1.0)),
                        ("rf", RandomForestRegressor(
                            n_estimators=300, min_samples_leaf=2,
                            n_jobs=-1, random_state=0))]:
        resid = np.full(len(df), np.nan)
        for tr, te in LeaveOneGroupOut().split(X, groups=groups):
            m = clone(model)
            m.fit(X[tr], (y - base)[tr])
            resid[te] = m.predict(X[te])
        pred = base + resid
        met = {"MAE_C": round(float(np.mean(np.abs(y - pred))), 3),
               "RMSE_C": round(float(np.sqrt(np.mean((y - pred) ** 2))), 3),
               "R2_residual": round(float(r2_score((y - base), resid)), 3)}
        out[f"delta_{name}"] = met
        print(f"delta-{name}: {met}")

    # feature importance (ridge) -- which sequence descriptor drives correction
    m = Ridge(alpha=1.0).fit(X, (y - base))
    imp = pd.Series(np.abs(m.coef_), index=FEATS).sort_values(ascending=False)
    out["top_features_ridge"] = imp.head(6).round(4).to_dict()
    print("top residual features:", out["top_features_ridge"])

    df.to_parquet(P4 / "delta_learning_dataset.parquet", index=False)
    (P4 / "p4_delta_learning.json").write_text(json.dumps(out, indent=2))
    print("saved", P4 / "p4_delta_learning.json")


if __name__ == "__main__":
    main()
